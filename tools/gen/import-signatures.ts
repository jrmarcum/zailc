// Derives src/gen/signatures.zig from upstream's generate_pizlonated_forwarders.rb: every
// `addSig` / `addOutSig` statement becomes one table row. The tables are DATA in that file, so they
// are imported mechanically rather than typed by hand; when upstream changes them, re-run this.
//
//   deno run -A tools/gen/import-signatures.ts [path/to/generate_pizlonated_forwarders.rb]
//
// Default input: the Fil-C source tree at FILC_SHA (tools/lib/tool.ts `filcSrc()`).

import { FILC_SHA, FILC_VERSION, REPO, filcSrc, linuxOnly, must, requireFilcSrc, zig, zigCacheArgs } from "../lib/tool.ts";

await linuxOnly(import.meta);

const rb = Deno.args[0] ?? `${await requireFilcSrc()}/libpas/src/libpas/generate_pizlonated_forwarders.rb`;
const text = await Deno.readTextFile(rb);
const lines = text.split("\n");

// Upstream's licence header: the `#` comment block after the shebang, kept in the output.
const notice: string[] = [];
for (const line of lines.slice(1)) {
  if (!line.startsWith("#")) break;
  notice.push(line.replace(/^#\s?/, "").trimEnd());
}

// Statements: `addSig …` / `addOutSig …`, continued while a line ends with a comma.
const stmts: string[] = [];
let cur = "";
for (const raw of lines) {
  const line = raw.trim();
  if (cur) cur += " " + line;
  else if (/^add(Out)?Sig\b/.test(line)) cur = line;
  else continue;
  if (cur.endsWith(",")) continue;
  stmts.push(cur);
  cur = "";
}
if (cur) throw new Error(`unterminated statement: ${cur}`);

/** `nil` and the "quoted" arguments of a statement, in order. */
function tokens(stmt: string): (string | null)[] {
  return [...stmt.matchAll(/\bnil\b|"((?:[^"\\]|\\.)*)"/g)].map((m) => (m[0] === "nil" ? null : m[1]));
}

interface Sig { cond: string | null; rets: string; name: string; args: string[] }
const natives: Sig[] = [];
const users: Sig[] = [];
for (const s of stmts) {
  const t = tokens(s);
  const str = (i: number): string => {
    const v = t[i];
    if (v === null || v === undefined) throw new Error(`bad statement: ${s}`);
    return v;
  };
  if (s.startsWith("addOutSig")) {
    users.push({ cond: null, name: str(0), rets: str(1), args: t.slice(2).map((_, i) => str(i + 2)) });
  } else {
    natives.push({ cond: t[0], rets: str(1), name: str(2), args: t.slice(3).map((_, i) => str(i + 3)) });
  }
}

const z = (s: string) => JSON.stringify(s); // the strings contain no escapes beyond quotes
function row(s: Sig): string {
  const f = [];
  if (s.cond !== null) f.push(`.cond = ${z(s.cond)}`);
  f.push(`.rets = ${z(s.rets)}`, `.name = ${z(s.name)}`);
  if (s.args.length) f.push(`.args = &.{ ${s.args.map(z).join(", ")} }`);
  return `    .{ ${f.join(", ")} },`;
}

const out = [
  "// GENERATED by tools/gen/import-signatures.ts. Do not edit: re-run the tool.",
  `// Source: Fil-C ${FILC_VERSION} (${FILC_SHA}), libpas/src/libpas/generate_pizlonated_forwarders.rb,`,
  `// its \`addSig\` / \`addOutSig\` statements (${natives.length} native, ${users.length} user). The emitters are`,
  "// src/gen/forwarders.zig. That file carries this notice, which applies to these tables too:",
  "//",
  ...notice.map((l) => (l ? `// ${l}` : "//")),
  "",
  'const Sig = @import("sig.zig").Sig;',
  "",
  "/// `addSig`: runtime functions callable from pizlonated code (`filc_native_*`).",
  "pub const natives = [_]Sig{",
  ...natives.map(row),
  "};",
  "",
  "/// `addOutSig`: the shapes of user functions the runtime calls (`filc_call_user_*`).",
  "pub const users = [_]Sig{",
  ...users.map(row),
  "};",
  "",
].join("\n");

const dest = `${REPO}/src/gen/signatures.zig`;
await Deno.writeTextFile(dest, out);
await must([zig(), "fmt", dest]);
console.log(`${dest}: ${natives.length} native + ${users.length} user signatures from ${rb}`);
if (Deno.args[0]) console.log(`note: input given explicitly; the default is ${filcSrc()} (${FILC_SHA})`);
void zigCacheArgs;
