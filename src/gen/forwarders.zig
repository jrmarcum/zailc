//! `filc_native.h` declares, and `filc_native_forwarders.c` defines, the thunks between Fil-C's
//! pizlonated calling convention and the runtime's C functions (`filc_native_*`), plus the
//! `filc_call_user_*` helpers the runtime uses to call into user code.
const std = @import("std");
const sig = @import("sig.zig");
const tables = @import("signatures.zig");

pub const Sig = sig.Sig;
pub const natives = tables.natives;
pub const users = tables.users;

const Allocator = std.mem.Allocator;
const Out = std.ArrayList(u8);

/// Kept word for word: the files must stay byte-identical to upstream's while zailc checks itself
/// against Ruby (cmem/design-decisions.md).
pub const banner = "/* Generated by generate_pizlonated_forwarders.rb */\n";

fn eql(a: []const u8, b: []const u8) bool {
    return std.mem.eql(u8, a, b);
}

/// `Signature#nativeReturnType`.
fn printNativeReturnType(out: *Out, gpa: Allocator, s: Sig) !void {
    if (s.throwsException()) {
        try out.print(gpa, "filc_exception_and_{s}", .{sig.underbarType(s.actualRets())});
    } else {
        try out.appendSlice(gpa, s.rets);
    }
}

/// The `src/libpas/filc_native.h` branch of the Ruby script.
pub fn writeHeader(out: *Out, gpa: Allocator) !void {
    try sig.validateAll(&natives, &users);
    try out.appendSlice(gpa, banner);
    try out.appendSlice(gpa, "#ifndef FILC_NATIVE_H\n#define FILC_NATIVE_H\n#include \"filc_runtime.h\"\nPAS_BEGIN_EXTERN_C;\n");
    for (natives) |s| {
        if (s.cond) |c| try out.print(gpa, "#if {s}\n", .{c});
        try out.appendSlice(gpa, "PAS_API ");
        try printNativeReturnType(out, gpa, s);
        try out.print(gpa, " filc_native_{s}(filc_thread* my_thread", .{s.name});
        for (s.args, 0..) |a, i| {
            if (eql(a, "...")) {
                try out.appendSlice(gpa, ", filc_cc_cursor* args_cursor");
            } else {
                try out.print(gpa, ", {s} arg{d}", .{ a, i });
            }
        }
        try out.appendSlice(gpa, ");\n");
        if (s.cond != null) try out.appendSlice(gpa, "#endif\n");
    }
    for (users) |s| {
        try out.appendSlice(gpa, "PAS_API ");
        try printNativeReturnType(out, gpa, s);
        try out.print(gpa, " filc_call_user_{s}(filc_thread* my_thread, filc_ptr target", .{s.name});
        for (s.args, 0..) |a, i| try out.print(gpa, ", {s} arg{d}", .{ a, i });
        try out.appendSlice(gpa, ");\n");
    }
    // Upstream closes the include guard BEFORE the extern-C block; reproduced as is.
    try out.appendSlice(gpa, "#endif /* FILC_NATIVE_H */\nPAS_END_EXTERN_C;\n");
}

/// The `src/libpas/filc_native_forwarders.c` branch of the Ruby script.
pub fn writeForwarders(out: *Out, gpa: Allocator) !void {
    try sig.validateAll(&natives, &users);
    try out.appendSlice(gpa, banner);
    try out.appendSlice(gpa, "#include \"pas_config.h\"\n#if LIBPAS_ENABLED && PAS_ENABLE_FILC\n#include \"filc_native.h\"\nPAS_BEGIN_EXTERN_C;\n");
    for (natives) |s| try writeNativeThunk(out, gpa, s);
    for (users) |s| try writeUserCall(out, gpa, s);
    try out.appendSlice(gpa, "PAS_END_EXTERN_C;\n#endif\n");
}

fn writeNativeThunk(out: *Out, gpa: Allocator, s: Sig) !void {
    const throws = s.throwsException();
    if (s.cond) |c| try out.print(gpa, "#if {s}\n", .{c});
    try out.print(gpa, "static pizlonated_return_value native_thunk_{s}(\n", .{s.name});
    try out.appendSlice(gpa, "    filc_thread* my_thread, void* callee_lower, size_t argument_size)\n{\n    PAS_UNUSED_PARAM(callee_lower);\n");
    if (throws) {
        try out.print(gpa, "    FILC_DEFINE_CATCHING_FRAME(\"{s}\");\n", .{s.name});
    } else {
        try out.print(gpa, "    FILC_DEFINE_FRAME(\"{s}\");\n", .{s.name});
    }
    try out.appendSlice(gpa, "    filc_native_frame native_frame;\n    filc_push_frame(my_thread, frame);\n    filc_push_native_frame(my_thread, &native_frame);\n    filc_cc_cursor args_cursor = filc_cc_cursor_create_begin(argument_size);\n");
    for (s.args, 0..) |a, i| {
        if (eql(a, "...")) continue;
        // The trailing space after `=` is upstream's.
        try out.print(gpa, "    {s} arg{d} = \n        filc_cc_cursor_get_next_{s}(\n            my_thread, &args_cursor);\n", .{ a, i, sig.underbarType(a) });
    }
    if (eql(s.rets, "void")) {
        try out.appendSlice(gpa, "    ");
    } else {
        try out.appendSlice(gpa, "    ");
        try printNativeReturnType(out, gpa, s);
        try out.appendSlice(gpa, " result = ");
    }
    try out.print(gpa, "filc_native_{s}(my_thread", .{s.name});
    for (s.args, 0..) |a, i| {
        if (eql(a, "...")) {
            try out.appendSlice(gpa, ", &args_cursor");
        } else {
            try out.print(gpa, ", arg{d}", .{i});
        }
    }
    try out.appendSlice(gpa, ");\n    filc_cc_sizer rets_sizer = filc_cc_sizer_create();\n");
    const actual = s.actualRets();
    if (eql(actual, "void")) {
        try out.appendSlice(gpa, "    filc_cc_sizer_add_int(&rets_sizer);\n    filc_cc_cursor rets_cursor =\n        filc_cc_sizer_get_cursor(my_thread, &rets_sizer);\n    filc_cc_cursor_set_next_int(my_thread, &rets_cursor, 0);\n");
    } else {
        const ub = sig.underbarType(actual);
        try out.print(gpa, "    filc_cc_sizer_add_{s}(&rets_sizer);\n    filc_cc_cursor rets_cursor =\n        filc_cc_sizer_get_cursor(my_thread, &rets_sizer);\n    filc_cc_cursor_set_next_{s}(\n        my_thread, &rets_cursor, {s});\n", .{ ub, ub, if (throws) "result.value" else "result" });
    }
    try out.appendSlice(gpa, "    filc_pop_native_frame(my_thread, &native_frame);\n    filc_pop_frame(my_thread, frame);\n    return pizlonated_return_value_create(");
    try out.appendSlice(gpa, if (throws) "result.has_exception, " else "false, ");
    try out.appendSlice(gpa, "filc_cc_sizer_total_size(&rets_sizer));\n}\n");
    const n = s.name;
    try out.print(gpa,
        \\static const filc_function_object function_object_{s} = {{
        \\    .object = {{
        \\        .upper = (void*)&function_object_{s}.function,
        \\        .aux = FILC_AUX_CREATE(
        \\            FILC_OBJECT_FLAGS_CREATE(
        \\                FILC_OBJECT_FLAG_GLOBAL |
        \\                FILC_OBJECT_FLAG_READONLY,
        \\                FILC_SPECIAL_TYPE_FUNCTION,
        \\                0),
        \\            (void*)&function_object_{s}.function)
        \\    }},
        \\    .function = {{
        \\        .fast_entrypoint = (void*)native_thunk_{s},
        \\        .generic_entrypoint = native_thunk_{s},
        \\        .signature = FILC_GENERIC_SIGNATURE
        \\    }}
        \\}};
        \\filc_ptr pizlonated_{s}(
        \\    filc_thread* my_thread, const filc_origin* origin)
        \\{{
        \\    PAS_UNUSED_PARAM(my_thread);
        \\    PAS_UNUSED_PARAM(origin);
        \\    return filc_ptr_create_with_object_and_ptr_and_manual_tracking(
        \\        (filc_object*)&function_object_{s}.object,
        \\        (void*)&function_object_{s}.function);
        \\}}
        \\
    , .{ n, n, n, n, n, n, n, n });
    if (s.cond != null) try out.appendSlice(gpa, "#endif\n");
}

fn writeUserCall(out: *Out, gpa: Allocator, s: Sig) !void {
    const throws = s.throwsException();
    try printNativeReturnType(out, gpa, s);
    try out.print(gpa, " filc_call_user_{s}(filc_thread* my_thread, filc_ptr target", .{s.name});
    for (s.args, 0..) |a, i| try out.print(gpa, ", {s} arg{d}", .{ a, i });
    try out.appendSlice(gpa, ")\n{\n");
    if (throws) {
        try out.appendSlice(gpa, "    PAS_TESTING_ASSERT(\n        filc_origin_get_function_origin(\n            my_thread->top_frame->origin)->can_catch);\n");
    }
    try out.appendSlice(gpa, "    filc_check_function_call(target);\n    filc_cc_sizer args_sizer = filc_cc_sizer_create();\n");
    for (s.args) |a| try out.print(gpa, "    filc_cc_sizer_add_{s}(&args_sizer);\n", .{sig.underbarType(a)});
    try out.appendSlice(gpa, "    filc_cc_cursor args_cursor =\n        filc_cc_sizer_get_cursor(my_thread, &args_sizer);\n");
    for (s.args, 0..) |a, i| {
        if (eql(a, "filc_ptr")) {
            try out.print(gpa, "    filc_thread_track_object(my_thread, filc_ptr_object(arg{d}));\n", .{i});
        }
        try out.print(gpa, "    filc_cc_cursor_set_next_{s}(\n        my_thread, &args_cursor, arg{d});\n", .{ sig.underbarType(a), i });
    }
    try out.appendSlice(gpa, "    filc_lock_top_native_frame(my_thread);\n    pizlonated_function target_function =\n        ((filc_function*)filc_ptr_ptr(target))->generic_entrypoint;\n    pizlonated_return_value return_value = target_function(\n        my_thread, filc_ptr_lower(target),\n        filc_cc_sizer_total_size(&args_sizer));\n");
    if (!throws) {
        try out.appendSlice(gpa, "    FILC_CHECK(!return_value.has_exception, NULL,\n               \"unexpected exception throw.\");\n");
    }
    try out.appendSlice(gpa, "    filc_unlock_top_native_frame(my_thread);\n");
    if (throws) {
        try out.appendSlice(gpa, "    if (return_value.has_exception)\n        return ");
        try printNativeReturnType(out, gpa, s);
        try out.appendSlice(gpa, "_with_exception();\n");
    }
    const actual = s.actualRets();
    const ub = sig.underbarType(actual);
    if (eql(actual, "void")) {
        if (throws) try out.appendSlice(gpa, "    return filc_exception_and_void_with_void();\n");
    } else {
        try out.appendSlice(gpa, "    filc_cc_cursor rets_cursor =\n        filc_cc_cursor_create_begin(return_value.return_size);\n");
        if (eql(actual, "filc_ptr")) {
            try out.appendSlice(gpa, "    filc_ptr result =\n        filc_cc_cursor_get_next_ptr(my_thread, &rets_cursor);\n    filc_thread_track_object(my_thread, filc_ptr_object(result));\n");
        } else {
            try out.print(gpa, "    {s} result =\n        filc_cc_cursor_get_next_{s}(\n            my_thread, &rets_cursor);\n", .{ actual, ub });
        }
        if (throws) {
            try out.appendSlice(gpa, "    return ");
            try printNativeReturnType(out, gpa, s);
            try out.print(gpa, "_with_{s}(result);\n", .{ub});
        } else {
            try out.appendSlice(gpa, "    return result;\n");
        }
    }
    try out.appendSlice(gpa, "}\n");
}

// ---------------------------------------------------------------------------------------------
// Tests: the bytes. SHA-256 of Ruby's output for Fil-C v0.686 (163fae5), measured 2026-10-08
// (`ruby src/libpas/generate_pizlonated_forwarders.rb ...`, ruby 3.3.8): filc_native.h is 493
// lines / 45,366 bytes; filc_native_forwarders.c is 24,139 lines / 976,926 bytes.
// ---------------------------------------------------------------------------------------------

pub const ruby_sha256_header = "8dbba1005797433f44f5487c6edd43d4ec17193e22cc1b0d257166aa98d15510";
pub const ruby_sha256_forwarders = "aa72d0dd1354db9acd4fbe99ae03417936a99f735fd4fdf5225bdccd072c595c";

fn expectSha256(bytes: []const u8, want_hex: []const u8) !void {
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    const got = std.fmt.bytesToHex(digest, .lower);
    try std.testing.expectEqualStrings(want_hex, &got);
}

test "the tables validate" {
    try sig.validateAll(&natives, &users);
    try std.testing.expectEqual(@as(usize, 453), natives.len);
    try std.testing.expectEqual(@as(usize, 13), users.len);
}

test "filc_native.h is byte-identical to Ruby's (v0.686)" {
    const gpa = std.testing.allocator;
    var out: Out = .empty;
    defer out.deinit(gpa);
    try writeHeader(&out, gpa);
    try std.testing.expectEqual(@as(usize, 45366), out.items.len);
    try expectSha256(out.items, ruby_sha256_header);
}

test "filc_native_forwarders.c is byte-identical to Ruby's (v0.686)" {
    const gpa = std.testing.allocator;
    var out: Out = .empty;
    defer out.deinit(gpa);
    try writeForwarders(&out, gpa);
    try std.testing.expectEqual(@as(usize, 976926), out.items.len);
    try expectSha256(out.items, ruby_sha256_forwarders);
}

